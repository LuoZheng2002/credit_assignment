#[derive(Parser, Debug)]
struct CliArgs {
    #[arg(short = 'c', long)]
    config_path: String,
    #[arg(long, default_value_t = false)]
    login_smoke: bool,
}

#[derive(Deserialize, Debug)]
#[serde(deny_unknown_fields)]
#[allow(dead_code)]
struct Args {
    model_cli_name: String,
    config_nickname_training: String,
    config_nickname_generation: String,
    use_tool: bool,
    num_oneshot_epochs: usize,
    #[serde(default)]
    validation_total_epochs: Option<usize>,
    validation_rollout_secs: usize,
    training_hyperparameters: TrainingHyperparameters,
    oneshot_per_epoch_training_time: f32,
    num_iterations_limit: usize,
    num_gpus: usize,
    inference_backend: InferenceBackend,
    training_trajectory_len_cutoff: usize,
    #[serde(default = "default_training_set_sort_mode")]
    training_set_sort_mode: TrainingSetSortMode,
    #[serde(default)]
    total_time_limit_hours: f32,
    mount_dir: String,
    generation_mount_dir: String,
}

fn default_training_set_sort_mode() -> TrainingSetSortMode {
    TrainingSetSortMode::ByQuestion
}

async fn run_oneshot_training<M: LlmModelMarker>(
    model_cli_name: &str,
    config_nickname_training: &str,
    config_nickname_generation: &str,
    generation_mount_dir: &str,
    mount_dir: &str,
    num_oneshot_epochs: usize,
    training_hyperparameters: TrainingHyperparameters,
    oneshot_per_epoch_training_time: f32,
    num_iterations_limit: usize,
    num_gpus: usize,
    training_trajectory_len_cutoff: usize,
    training_set_sort_mode: TrainingSetSortMode,
    training_wrapper_log_path: &str,
) {
    // Resolve one-shot paths (use rollout mount dir to find trajectories on the rollout volume)
    let oneshot_trajectories_dir = training_trajectories_oneshot_path(
        generation_mount_dir,
        model_cli_name,
        config_nickname_generation,
    );
    let kl_enabled = training_hyperparameters.kl_beta > 0.0;
    let oneshot_trajectories_msgpack_path = if kl_enabled {
        training_trajectories_oneshot_ref_logprobs_path(&oneshot_trajectories_dir)
    } else {
        Path::new(&oneshot_trajectories_dir)
            .join("trajectories.msgpack")
            .to_string_lossy()
            .into_owned()
    };

    let first_expected_chunk_path = if kl_enabled {
        training_trajectories_oneshot_chunk_ref_logprobs_path(&oneshot_trajectories_dir, 0)
    } else {
        training_trajectories_oneshot_chunk_path(&oneshot_trajectories_dir, 0)
    };

    // Training trajectories must be pre-generated by the oneshot generation binary.
    if !Path::new(&oneshot_trajectories_msgpack_path).exists()
        && !Path::new(&first_expected_chunk_path).exists()
    {
        panic!(
            "Training trajectories not found at '{}' or first chunk '{}'. \
             Run bin_oneshot_generation first. If kl_beta > 0, run the reference-logprob annotation pass before training.",
            oneshot_trajectories_msgpack_path, first_expected_chunk_path
        );
    }
    log_info(format!(
        "Using pre-generated training trajectories from {}",
        oneshot_trajectories_dir
    ));

    let oneshot_training_summary_parent_dir =
        training_summary_oneshot_parent_dir(mount_dir, model_cli_name, config_nickname_training);
    // ================================================================
    // Phase 1: Train all oneshot epochs. Chunk-backed training launches one
    // Python process per epoch; Python persists epoch-boundary optimizer/status
    // state next to the model checkpoint and falls back to fresh optimizer state
    // if a legacy checkpoint has no status file.
    // ================================================================

    let oneshot_model_output_root =
        oneshot_epochs_parent_dir(mount_dir, model_cli_name, config_nickname_training);

    let base_model_parent_dir = base_model_dir(mount_dir, model_cli_name);
    let mut training_base_model_parent_dir = base_model_parent_dir.clone();
    let mut start_epoch = 1usize;

    let previous_artifacts_detected = detect_oneshot_artifacts(
        &oneshot_training_summary_parent_dir,
        &oneshot_model_output_root,
    );
    if previous_artifacts_detected {
        let previous_num_oneshot_epochs =
            read_oneshot_run_manifest(&oneshot_training_summary_parent_dir)
                .map(|manifest| manifest.num_oneshot_epochs)
                .or_else(|| {
                    read_oneshot_epoch_count_from_summary(&oneshot_training_summary_parent_dir)
                });

        match previous_num_oneshot_epochs {
            Some(previous_num_oneshot_epochs) if previous_num_oneshot_epochs != num_oneshot_epochs => {
                log_warning(format!(
                    "Detected prior oneshot artifacts with num_oneshot_epochs={} but current request uses {}; continuing so training can append additional epochs when possible.",
                    previous_num_oneshot_epochs, num_oneshot_epochs
                ));
            }
            None => {
                log_warning(format!(
                    "Detected prior oneshot artifacts under {} but could not determine the previous num_oneshot_epochs; continuing with current request num_oneshot_epochs={}.",
                    oneshot_model_output_root, num_oneshot_epochs
                ));
            }
            _ => {}
        }
        write_oneshot_run_manifest(&oneshot_training_summary_parent_dir, num_oneshot_epochs);

        let completed_epochs =
            count_contiguous_ready_oneshot_epochs(&oneshot_model_output_root, num_oneshot_epochs);
        if completed_epochs >= num_oneshot_epochs
            && all_expected_oneshot_model_outputs_exist(
                &oneshot_model_output_root,
                num_oneshot_epochs,
            )
        {
            log_info(format!(
                "Detected matching prior oneshot artifacts for num_oneshot_epochs={}; skipping training",
                num_oneshot_epochs
            ));
            let training_epoch_stats =
                read_oneshot_training_epoch_stats(&oneshot_model_output_root, num_oneshot_epochs);
            log_info(format!(
                "Recorded per-epoch training stats for {} oneshot epoch(s)",
                training_epoch_stats.throughputs.len()
            ));
            log_state("One-shot training completed");
            return;
        }
        start_epoch = completed_epochs + 1;
        if completed_epochs > 0 {
            training_base_model_parent_dir = format!(
                "{}/oneshot_epoch_{}",
                oneshot_model_output_root, completed_epochs
            );
        }
        log_warning(format!(
            "Detected partial oneshot artifacts; resuming training from epoch {} of {} using base model parent {}",
            start_epoch, num_oneshot_epochs, training_base_model_parent_dir
        ));
    } else {
        write_oneshot_run_manifest(&oneshot_training_summary_parent_dir, num_oneshot_epochs);
    }

    if start_epoch <= num_oneshot_epochs {
        log_state(format!(
            "Starting oneshot training from epoch {} through {}",
            start_epoch, num_oneshot_epochs
        ));

        let training_start_time = Instant::now();
        let first_chunk_path = first_expected_chunk_path.clone();
        if Path::new(&first_chunk_path).exists() {
            log_info(format!(
                "Detected chunked one-shot trajectories; using one trajectory chunk per epoch from {}",
                oneshot_trajectories_dir
            ));
            for epoch in start_epoch..=num_oneshot_epochs {
                let chunk_index = epoch - 1;
                let chunk_path = if kl_enabled {
                    training_trajectories_oneshot_chunk_ref_logprobs_path(
                        &oneshot_trajectories_dir,
                        chunk_index,
                    )
                } else {
                    training_trajectories_oneshot_chunk_path(
                        &oneshot_trajectories_dir,
                        chunk_index,
                    )
                };
                if !Path::new(&chunk_path).exists() {
                    panic!(
                        "Trajectory chunk for epoch {} not found at {}; generation must produce one chunk per requested epoch, and KL-enabled training requires the reference-logprob annotation pass",
                        epoch, chunk_path
                    );
                }
                let chunk_base_model_parent_dir = if epoch == 1 {
                    base_model_parent_dir.clone()
                } else {
                    format!("{}/oneshot_epoch_{}", oneshot_model_output_root, epoch - 1)
                };
                let training_config = PythonTrainingConfig {
                    hyperparameters: training_hyperparameters.clone(),
                    num_iterations_limit,
                    training_trajectory_len_cutoff,
                    training_set_sort_mode: format!("{:?}", TrainingSetSortMode::ByQuestion),
                    model_cli_name: model_cli_name.to_string(),
                    config_nickname: config_nickname_training.to_string(),
                    training_mode: TrainingMode::OneShot {
                        per_epoch_training_time: oneshot_per_epoch_training_time,
                        num_oneshot_epochs: epoch,
                        start_epoch: epoch,
                        model_output_root: oneshot_model_output_root.clone(),
                        training_summary_dir: oneshot_model_output_root.clone(),
                        base_model_parent_dir: chunk_base_model_parent_dir,
                    },
                };
                log_info(format!(
                    "Starting chunk-backed epoch {} with trajectory chunk {}",
                    epoch, chunk_path
                ));
                run_training_wrapper_and_wait(
                    num_gpus,
                    M::API_NAME,
                    &training_config,
                    &chunk_path,
                    training_wrapper_log_path,
                )
                .await
                .unwrap_or_else(|err| panic!("Oneshot chunk-backed training failed: {}", err));
            }
        } else {
            let training_config = PythonTrainingConfig {
                hyperparameters: training_hyperparameters.clone(),
                num_iterations_limit,
                training_trajectory_len_cutoff,
                training_set_sort_mode: format!("{:?}", training_set_sort_mode),
                model_cli_name: model_cli_name.to_string(),
                config_nickname: config_nickname_training.to_string(),
                training_mode: TrainingMode::OneShot {
                    per_epoch_training_time: oneshot_per_epoch_training_time,
                    num_oneshot_epochs,
                    start_epoch,
                    model_output_root: oneshot_model_output_root.clone(),
                    training_summary_dir: oneshot_model_output_root.clone(),
                    base_model_parent_dir: training_base_model_parent_dir,
                },
            };

            run_training_wrapper_and_wait(
                num_gpus,
                M::API_NAME,
                &training_config,
                &oneshot_trajectories_msgpack_path,
                training_wrapper_log_path,
            )
            .await
            .unwrap_or_else(|err| panic!("Oneshot training failed: {}", err));
        }
        let elapsed_secs = training_start_time.elapsed().as_secs_f32();
        log_info(format!(
            "Oneshot training of {} epoch(s) finished in {:.3}s",
            num_oneshot_epochs, elapsed_secs
        ));
    }
    let training_epoch_stats =
        read_oneshot_training_epoch_stats(&oneshot_model_output_root, num_oneshot_epochs);
    log_info(format!(
        "Recorded per-epoch training stats for {} oneshot epoch(s)",
        training_epoch_stats.throughputs.len()
    ));
    log_state("One-shot training completed");
}

#[tokio::main(flavor = "multi_thread", worker_threads = 4)]
async fn main() {
    std::panic::set_hook(Box::new(|info| {
        eprintln!("panic occurred: {}", info);
        let rust_backtrace = std::env::var("RUST_BACKTRACE").ok();
        if matches!(rust_backtrace.as_deref(), Some("1") | Some("full")) {
            let backtrace = Backtrace::force_capture();
            eprintln!("backtrace:\n{}", backtrace);
        }
        std::process::abort();
    }));
    dotenvy::dotenv().ok();
    let CliArgs {
        config_path,
        login_smoke,
    } = CliArgs::parse();
    let config_contents = std::fs::read_to_string(&config_path)
        .unwrap_or_else(|err| panic!("failed to read config file '{}': {}", config_path, err));
    let Args {
        model_cli_name,
        config_nickname_training,
        config_nickname_generation,
        use_tool: _,
        num_oneshot_epochs,
        training_hyperparameters,
        oneshot_per_epoch_training_time,
        num_iterations_limit,
        num_gpus,
        training_trajectory_len_cutoff,
        training_set_sort_mode,
        mount_dir,
        generation_mount_dir,
        ..
    } = toml::from_str(&config_contents)
        .unwrap_or_else(|err| panic!("failed to parse config file '{}': {}", config_path, err));
    let process_title = format!(
        "oneshot_training_{}_{}",
        model_cli_name, config_nickname_training
    );
    set_title(&process_title);
    check_sympy_availability().unwrap();
    assert!(num_gpus > 0, "--num-gpus must be positive");
    assert!(
        num_oneshot_epochs > 0,
        "--num-oneshot-epochs must be positive"
    );
    let model_name = LlmModelName::from_str(&model_cli_name, true).unwrap();
    if login_smoke {
        println!(
            "login-smoke passed for bin_oneshot_training: model={}, training_config={}, generation_config={}, num_epochs={}, num_gpus={}",
            model_cli_name,
            config_nickname_training,
            config_nickname_generation,
            num_oneshot_epochs,
            num_gpus
        );
        return;
    }
    configure_mount_dir(&mount_dir)
        .unwrap_or_else(|err| panic!("failed to configure mount dir: {}", err));
    let training_wrapper_log_path =
        training_wrapper_log_path(&mount_dir, &model_cli_name, &config_nickname_training);
    ensure_parent_dir_exists(&training_wrapper_log_path)
        .unwrap_or_else(|err| panic!("failed to prepare training wrapper log directory: {}", err));
    log_info(format!("One-shot training will use num_gpus={}", num_gpus));

    let text_log_summary_path =
        text_logger_summary_path(&mount_dir, &model_cli_name, &config_nickname_training);
    let text_log_verbose_path =
        text_logger_verbose_path(&mount_dir, &model_cli_name, &config_nickname_training);
    ProgressTextLogger::initialize(text_log_summary_path, text_log_verbose_path)
        .await
        .unwrap();

    match model_name {
        LlmModelName::Gemma3_4b => {
            run_oneshot_training::<Gemma3_4BIt>(
                &model_cli_name,
                &config_nickname_training,
                &config_nickname_generation,
                &generation_mount_dir,
                &mount_dir,
                num_oneshot_epochs,
                training_hyperparameters,
                oneshot_per_epoch_training_time,
                num_iterations_limit,
                num_gpus,
                training_trajectory_len_cutoff,
                training_set_sort_mode,
                &training_wrapper_log_path,
            )
            .await
        }
        LlmModelName::Llama31_8b => {
            run_oneshot_training::<Llama31_8BInstruct>(
                &model_cli_name,
                &config_nickname_training,
                &config_nickname_generation,
                &generation_mount_dir,
                &mount_dir,
                num_oneshot_epochs,
                training_hyperparameters,
                oneshot_per_epoch_training_time,
                num_iterations_limit,
                num_gpus,
                training_trajectory_len_cutoff,
                training_set_sort_mode,
                &training_wrapper_log_path,
            )
            .await
        }
        LlmModelName::Mistral7bInstructV03 => {
            run_oneshot_training::<Mistral7BInstructV03>(
                &model_cli_name,
                &config_nickname_training,
                &config_nickname_generation,
                &generation_mount_dir,
                &mount_dir,
                num_oneshot_epochs,
                training_hyperparameters,
                oneshot_per_epoch_training_time,
                num_iterations_limit,
                num_gpus,
                training_trajectory_len_cutoff,
                training_set_sort_mode,
                &training_wrapper_log_path,
            )
            .await
        }
        LlmModelName::Qwen3_06b => {
            run_oneshot_training::<Qwen3_06B>(
                &model_cli_name,
                &config_nickname_training,
                &config_nickname_generation,
                &generation_mount_dir,
                &mount_dir,
                num_oneshot_epochs,
                training_hyperparameters,
                oneshot_per_epoch_training_time,
                num_iterations_limit,
                num_gpus,
                training_trajectory_len_cutoff,
                training_set_sort_mode,
                &training_wrapper_log_path,
            )
            .await
        }
        LlmModelName::Qwen3_4b => {
            run_oneshot_training::<Qwen3_4B>(
                &model_cli_name,
                &config_nickname_training,
                &config_nickname_generation,
                &generation_mount_dir,
                &mount_dir,
                num_oneshot_epochs,
                training_hyperparameters,
                oneshot_per_epoch_training_time,
                num_iterations_limit,
                num_gpus,
                training_trajectory_len_cutoff,
                training_set_sort_mode,
                &training_wrapper_log_path,
            )
            .await
        }
        LlmModelName::Qwen25_7b => {
            run_oneshot_training::<Qwen25_7B>(
                &model_cli_name,
                &config_nickname_training,
                &config_nickname_generation,
                &generation_mount_dir,
                &mount_dir,
                num_oneshot_epochs,
                training_hyperparameters,
                oneshot_per_epoch_training_time,
                num_iterations_limit,
                num_gpus,
                training_trajectory_len_cutoff,
                training_set_sort_mode,
                &training_wrapper_log_path,
            )
            .await
        }
        LlmModelName::Qwen35_08b => {
            run_oneshot_training::<Qwen35_08B>(
                &model_cli_name,
                &config_nickname_training,
                &config_nickname_generation,
                &generation_mount_dir,
                &mount_dir,
                num_oneshot_epochs,
                training_hyperparameters,
                oneshot_per_epoch_training_time,
                num_iterations_limit,
                num_gpus,
                training_trajectory_len_cutoff,
                training_set_sort_mode,
                &training_wrapper_log_path,
            )
            .await
        }
        LlmModelName::Qwen35_4b => {
            run_oneshot_training::<Qwen35_4B>(
                &model_cli_name,
                &config_nickname_training,
                &config_nickname_generation,
                &generation_mount_dir,
                &mount_dir,
                num_oneshot_epochs,
                training_hyperparameters,
                oneshot_per_epoch_training_time,
                num_iterations_limit,
                num_gpus,
                training_trajectory_len_cutoff,
                training_set_sort_mode,
                &training_wrapper_log_path,
            )
            .await
        }
    }

    ProgressTextLogger::shutdown().await.unwrap();
}
